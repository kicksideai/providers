local test = require("test")
local registry = require("registry")
local function define_tests()
    test.describe("Instance endpoints", function()
        test.it("declares official defaults through namespace requirements", function()
            local r = registry.get("kickside.atlassian:endpoint_resources")
            test.not_nil(r)
            test.eq(r.data.default, "https://api.atlassian.com/oauth/token/accessible-resources")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.atlassian:endpoint_gateway")
            test.not_nil(r)
            test.eq(r.data.default, "https://api.atlassian.com")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.atlassian:endpoint_authorization")
            test.not_nil(r)
            test.eq(r.data.default, "https://auth.atlassian.com/authorize")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.atlassian:endpoint_token")
            test.not_nil(r)
            test.eq(r.data.default, "https://auth.atlassian.com/oauth/token")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.atlassian:endpoint_userinfo")
            test.not_nil(r)
            test.eq(r.data.default, "https://api.atlassian.com/me")
            test.is_true(#r.data.targets > 0)
        end)
    end)
end
local cases = test.run_cases(define_tests)
return { run = function(options) return cases(options) end }
