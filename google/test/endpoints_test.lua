local test = require("test")
local registry = require("registry")
local function define_tests()
    test.describe("Instance endpoints", function()
        test.it("declares official defaults through namespace requirements", function()
            local r = registry.get("kickside.google:endpoint_drive")
            test.not_nil(r)
            test.eq(r.data.default, "https://www.googleapis.com/drive/v3")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.google:endpoint_sheets")
            test.not_nil(r)
            test.eq(r.data.default, "https://sheets.googleapis.com/v4/spreadsheets")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.google:endpoint_userinfo")
            test.not_nil(r)
            test.eq(r.data.default, "https://www.googleapis.com/oauth2/v2/userinfo")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.google:endpoint_analytics_admin")
            test.not_nil(r)
            test.eq(r.data.default, "https://analyticsadmin.googleapis.com/v1beta")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.google:endpoint_analytics_data")
            test.not_nil(r)
            test.eq(r.data.default, "https://analyticsdata.googleapis.com/v1beta")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.google:endpoint_gmail")
            test.not_nil(r)
            test.eq(r.data.default, "https://gmail.googleapis.com/gmail/v1/users/me")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.google:endpoint_contacts")
            test.not_nil(r)
            test.eq(r.data.default, "https://people.googleapis.com/v1")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.google:endpoint_docs")
            test.not_nil(r)
            test.eq(r.data.default, "https://docs.googleapis.com/v1")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.google:endpoint_calendar")
            test.not_nil(r)
            test.eq(r.data.default, "https://www.googleapis.com/calendar/v3")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.google:endpoint_slides")
            test.not_nil(r)
            test.eq(r.data.default, "https://slides.googleapis.com/v1/presentations")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.google:endpoint_authorization")
            test.not_nil(r)
            test.eq(r.data.default, "https://accounts.google.com/o/oauth2/v2/auth")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.google:endpoint_token")
            test.not_nil(r)
            test.eq(r.data.default, "https://oauth2.googleapis.com/token")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.google:endpoint_userinfo")
            test.not_nil(r)
            test.eq(r.data.default, "https://www.googleapis.com/oauth2/v2/userinfo")
            test.is_true(#r.data.targets > 0)
        end)
    end)
end
local cases = test.run_cases(define_tests)
return { run = function(options) return cases(options) end }
