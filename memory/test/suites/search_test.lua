local test = require("test")
local fixture = require("fixture")
local json = require("json")

local function define_tests()
    test.describe("memory search", function()

        test.it("publishes a staged revision vector only when its accepted item folds", function()
            local user = fixture.user()
            local id = fixture.memory(user)
            local added = fixture.create_claim(user, id, "Paris")
            local result, err = fixture.persistence_op(user, "revision_race", { component_id = id, item_id = added.item_id })
            test.is_nil(err, tostring(err))
            test.eq(result.staged_hash, result.original_hash)
            test.eq(result.vector_hash, result.item.content_hash)
            test.eq(result.item.content, "Revised presentation.")
        end)

        test.it("stores embeddings with payloads and preserves search through replay", function()
            local user = fixture.user()
            local id = fixture.memory(user)
            local added = fixture.create_claim(user, id, "Paris")
            fixture.settle(user, id)
            local db = fixture.db()
            local payloads, read_err = db:query("SELECT embedding, content_hash FROM kickside_memory_payloads WHERE component_id = $1 AND item_id = $2", { id, added.item_id })
            db:release()
            test.is_nil(read_err, tostring(read_err))
            test.eq(#json.decode(payloads[1].embedding), 512)
            local replayed, replay_err = fixture.persistence_op(user, "replay", { component_id = id })
            test.is_nil(replay_err, tostring(replay_err))
            test.not_nil(replayed)
            local nearest, nearest_err = fixture.persistence_op(user, "nearest", { component_id = id, content = "The current city is Paris." })
            test.is_nil(nearest_err, tostring(nearest_err))
            test.eq(nearest[1].id, added.item_id)
            test.is_true(nearest[1].similarity > 0.99)
        end)

        test.it("uses the shared cosine threshold without rewriting its score", function()
            local user = fixture.user()
            local id = fixture.memory(user)
            local added = fixture.create_claim(user, id, "Paris")
            local stored, stored_err = fixture.op(user, "get", { component_id = id, item_id = added.item_id })
            test.is_nil(stored_err, tostring(stored_err))
            local stored_vector, query_vector = {}, {}
            for i = 1, 512 do
                stored_vector[i] = i == 1 and 2 or 0
                query_vector[i] = i == 2 and 4 or 0
            end
            local _, replace_err = fixture.persistence_op(user, "set_vector", {
                component_id = id, item_id = added.item_id, vector = stored_vector, content_hash = stored.content_hash,
            })
            test.is_nil(replace_err, tostring(replace_err))
            local matches, search_err = fixture.persistence_op(user, "search_vector", {
                component_id = id, vector = query_vector, min_similarity = -0.1,
            })
            test.is_nil(search_err, tostring(search_err))
            test.eq(#matches, 1)
            test.eq(matches[1].id, added.item_id)
            test.is_true(math.abs(matches[1].similarity) < 0.000001)
        end)

        test.it("keeps lexical search on the newest revision after older and repeated delivery", function()
            local user = fixture.user()
            local id = fixture.memory(user)
            local added = fixture.create_claim(user, id, "Paris")
            local _, err = fixture.persistence_op(user, "revision_redelivery", { component_id = id, item_id = added.item_id })
            test.is_nil(err, tostring(err))
            local matches, match_err = fixture.persistence_op(user, "lexical", { component_id = id, query = "newestword" })
            test.is_nil(match_err, tostring(match_err))
            test.eq(#matches, 1)
            local stale, stale_err = fixture.persistence_op(user, "lexical", { component_id = id, query = "olderword" })
            test.is_nil(stale_err, tostring(stale_err))
            test.eq(#stale, 0)
        end)

        test.it("replays revision text, hashes and priority identically", function()
            local user = fixture.user()
            local id = fixture.memory(user)
            local added = fixture.create_claim(user, id, "Paris")
            local _, err = fixture.op(user, "edit", { component_id = id, item_id = added.item_id,
                fields = { content = "The user resides in Paris, France.", priority = 7 } })
            test.is_nil(err, tostring(err))
            fixture.settle(user, id)
            local before = fixture.items(user, id)
            local _, replay_err = fixture.persistence_op(user, "replay", { component_id = id })
            test.is_nil(replay_err, tostring(replay_err))
            test.eq(json.encode(fixture.items(user, id)), (json.encode(before)))
            test.eq(fixture.count_rows("kickside_memory_payloads", id), 2)
            local _, forget_err = fixture.op(user, "forget", { component_id = id, item_id = added.item_id })
            test.is_nil(forget_err, tostring(forget_err))
            fixture.settle(user, id)
            local erased = fixture.items(user, id)
            local _, erased_replay_err = fixture.persistence_op(user, "replay", { component_id = id })
            test.is_nil(erased_replay_err, tostring(erased_replay_err))
            test.eq(json.encode(fixture.items(user, id)), (json.encode(erased)))
        end)

        test.it("searches revised text and value-only edits with the resulting embedding", function()
            local user = fixture.user()
            local id = fixture.memory(user)
            local first = fixture.create_claim(user, id, "Paris", "multi")
            fixture.create_claim(user, id, "Berlin", "multi")
            local revised_text = "Orchids grow beneath tropical waterfalls."
            local revised, err = fixture.op(user, "edit", { component_id = id, item_id = first.item_id, fields = { content = revised_text } })
            test.is_nil(err, tostring(err))
            fixture.settle(user, id)
            local nearest, nearest_err = fixture.persistence_op(user, "nearest", { component_id = id, content = revised_text })
            test.is_nil(nearest_err, tostring(nearest_err))
            test.eq(nearest[1].id, revised.item_id)
            test.is_true(nearest[1].similarity > 0.99)
            local changed, change_err = fixture.op(user, "edit", { component_id = id, item_id = revised.item_id, fields = { value = "Rome" } })
            test.is_nil(change_err, tostring(change_err))
            fixture.settle(user, id)
            nearest, nearest_err = fixture.persistence_op(user, "nearest", { component_id = id, content = revised_text })
            test.is_nil(nearest_err, tostring(nearest_err))
            test.eq(nearest[1].id, changed.item_id)
            test.is_true(nearest[1].similarity > 0.99)
        end)

        test.it("does not reinsert embeddings from an erased or revised snapshot", function()
            local user = fixture.user()
            local id = fixture.memory(user)
            local first = fixture.create_claim(user, id, "Paris")
            local before = fixture.op(user, "get", { component_id = id, item_id = first.item_id })
            local _, edit_err = fixture.op(user, "edit", { component_id = id, item_id = first.item_id, fields = { content = "The user resides in Paris." } })
            test.is_nil(edit_err, tostring(edit_err))
            fixture.settle(user, id)
            local revised, err = fixture.persistence_op(user, "reembed", { component_id = id, item_id = first.item_id, content = before.content, content_hash = before.content_hash })
            test.is_nil(err, tostring(err))
            test.eq(revised, false)
            local _, forget_err = fixture.op(user, "forget", { component_id = id, item_id = first.item_id })
            test.is_nil(forget_err, tostring(forget_err))
            fixture.settle(user, id)
            local erased, erase_err = fixture.persistence_op(user, "reembed", { component_id = id, item_id = first.item_id, content = before.content, content_hash = before.content_hash })
            test.is_nil(erase_err, tostring(erase_err))
            test.eq(erased, false)
            test.eq(fixture.count_rows("kickside_memory_embeddings", id), 0)
        end)
    end)
end

local run_cases = test.run_cases(define_tests)
return { run = function(options) return run_cases(options) end }
