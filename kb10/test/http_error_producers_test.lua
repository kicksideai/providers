local test = require("test")
local kb_nodes = require("kb_nodes")
local writer = require("writer")
local uuid = require("uuid")
return test.run_cases(function()
    test.describe("KB10 refusal ownership", function()
        test.it("types a missing KB id at the resolver", function()
            local _, _, _, err = kb_nodes.resolve("")
            test.is_true(errors.is(err, errors.INVALID))
        end)
        test.it("types node input validation at the producer", function()
            local _, err = kb_nodes.get_node("kb", "")
            test.is_true(errors.is(err, errors.INVALID))
        end)
        test.it("retains typed refusals through transaction rollback", function()
            local component_id = uuid.v7()
            local store_id, create_err = writer.create_store(component_id, "model", {}, {})
            test.is_nil(create_err)
            local _, edge_err = writer.insert_edge(store_id, { edge_type = "relates", from_node_id = uuid.v7(), to_node_id = uuid.v7() })
            test.is_true(errors.is(edge_err, errors.NOT_FOUND))
            local _, invalid = writer.insert_edge(store_id, {})
            test.is_true(errors.is(invalid, errors.INVALID))
            local root, root_err = writer.insert_node(store_id, { node_type = "concept", content = "Root", metadata = { is_root = true } })
            test.is_nil(root_err)
            local removed, refusal = writer.delete_node(store_id, root)
            test.is_false(removed)
            test.is_true(errors.is(refusal, errors.INVALID))
            local _, delete_err = writer.delete_store(component_id)
            test.is_nil(delete_err)
        end)
    end)
end)
