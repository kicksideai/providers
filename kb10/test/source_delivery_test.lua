local test = require("test")
local source = require("source")
local fixture = require("fixture")

local function exercise(access_error, delivery_error, metadata)
    fixture.reset(access_error, delivery_error, metadata)
    source.handler()
    return fixture.status, fixture.body, fixture.calls, fixture.upload_id, fixture.expiration
end

return test.run_cases(function()
    test.describe("knowledge original delivery", function()
        test.it("returns the storage delivery URL and unchanged source metadata", function()
            local status, body, calls, id, expiration = exercise()
            test.eq(200, status)
            test.is_true(body.success)
            test.eq("https://objects.example/original.pdf?signature=test", body.url)
            test.eq("document.pdf", body.filename)
            test.eq("application/pdf", body.content_type)
            test.eq(1, calls)
            test.eq("original", id)
            test.eq(300, expiration)
        end)
        test.it("resolves the existing source_ref lineage", function()
            local status, body, _, id = exercise(nil, nil, {source_ref = {upload_id = "nested-original"}, filename = "nested.pdf", source_mime = "application/pdf"})
            test.eq(200, status)
            test.eq("nested-original", id)
            test.eq("nested.pdf", body.filename)
        end)
        test.it("denies delivery before resolving the upload when KB read is denied", function()
            local status, body, calls, id = exercise(errors.new({kind = errors.PERMISSION_DENIED, message = "read denied"}))
            test.eq(403, status)
            test.is_false(body.success)
            test.eq(0, calls)
            test.is_nil(id)
        end)
        test.it("reports delivery failure without returning a raw URL", function()
            local status, body = exercise(nil, errors.new({kind = errors.UNAVAILABLE, message = "signing unavailable"}))
            test.eq(500, status)
            test.is_false(body.success)
            test.is_nil(body.url)
        end)
    end)
end)
