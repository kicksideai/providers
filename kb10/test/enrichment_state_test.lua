local test = require("test")
local state = require("enrichment_state")
local component = require("component_fixture")
local function define_tests()
    test.describe("enrichment state reads", function()
        test.it("preserves component service failures when clearing", function()
            local cause = errors.new({ message = "component service unavailable", kind = errors.UNAVAILABLE })
            local fixture: any = { service_error = cause }
            component.set(fixture)
            local out, err = state.run({ component_id = "kb", clear = "all" })
            test.is_nil(out)
            test.eq(err, cause)
            test.is_nil(fixture.writes)
        end)
        test.it("preserves metadata read failures instead of reporting a skipped clear", function()
            local cause = errors.new({ message = "metadata unavailable", kind = errors.UNAVAILABLE })
            local fixture: any = { read_error = cause }
            component.set(fixture)
            local out, err = state.run({ component_id = "kb", clear = "error" })
            test.is_nil(out)
            test.eq(err, cause)
            test.is_nil(fixture.writes)
        end)
        test.it("skips a successful read with no enrichment flags", function()
            local fixture: any = { component = { meta = {} } }
            component.set(fixture)
            local out, err = state.run({ component_id = "kb", clear = "all" })
            test.is_nil(err)
            test.is_true(out.skipped)
            test.is_nil(fixture.writes)
        end)
        test.it("clears flags without changing unrelated metadata", function()
            local fixture: any = { component = { meta = { enrichment_error = "failed", enrichment_agent_missing = true, title = "Knowledge" } } }
            component.set(fixture)
            local out, err = state.run({ component_id = "kb", clear = "all" })
            test.is_nil(err)
            test.is_true(out.ok)
            test.eq(fixture.writes, 1)
            test.eq(fixture.fields.enrichment_error, "")
            test.is_false(fixture.fields.enrichment_agent_missing)
            test.is_nil(fixture.fields.title)
        end)
        test.it("preserves metadata write failures", function()
            local cause = errors.new({ message = "write unavailable", kind = errors.UNAVAILABLE })
            component.set({ write_error = cause })
            local out, err = state.run({ component_id = "kb", error = "failed" })
            test.is_nil(out)
            test.eq(err, cause)
        end)
    end)
end
return { run = test.run_cases(define_tests) }
