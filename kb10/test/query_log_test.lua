local test = require("test")
local uuid = require("uuid")
local sql = require("sql")
local log = require("query_log")
local store = require("store")

local function define_tests()
    test.describe("retrieval observation persistence", function()
        test.it("deletes observations and tuning state with the store even without connection-level cascades", function()
            local id = uuid.v7()
            local db, db_err = sql.get("app:db")
            test.is_nil(db_err)
            local db_type, type_err = db:type()
            test.is_nil(type_err)
            if db_type == sql.type.SQLITE then
                local _, pragma_err = db:execute("PRAGMA foreign_keys=OFF")
                test.is_nil(pragma_err)
            end
            db:release()
            local _, create_err = store.create_store(id, "class:embed", {}, nil)
            test.is_nil(create_err)
            local _, record_err = log.record(id, { query = "query", strategy = "plain", top_score = 0.1, results = 0 })
            test.is_nil(record_err)
            local _, delete_err = store.delete_store(id)
            test.is_nil(delete_err)
            db, db_err = sql.get("app:db")
            test.is_nil(db_err)
            if db_type == sql.type.SQLITE then
                local _, pragma_err = db:execute("PRAGMA foreign_keys=ON")
                test.is_nil(pragma_err)
            end
            local rows, read_err = db:query("SELECT COUNT(*) AS total FROM kb10_query_log WHERE store_id = $1", { id })
            local state, state_err = db:query("SELECT COUNT(*) AS total FROM kb10_tuning_state WHERE store_id = $1", { id })
            db:release()
            test.is_nil(read_err); test.is_nil(state_err)
            test.eq(rows[1].total, 0); test.eq(state[1].total, 0)
        end)
        test.it("rejects config writes after a concurrent save or a lost tuning lease", function()
            local id = uuid.v7()
            local _, create_err = store.create_store(id, "class:embed", { self_tuning = true }, nil)
            test.is_nil(create_err)
            local initial, initial_err = store.get_store(id)
            test.is_nil(initial_err)
            test.not_nil(initial.config_snapshot)
            local _, save_err = store.update_config(id, { self_tuning = false, user_setting = "saved" })
            test.is_nil(save_err)
            local applied, conflict = store.update_config(id, { self_tuning = true }, initial.config_snapshot)
            test.is_nil(applied)
            test.eq(conflict:kind(), errors.CONFLICT)
            local fresh, read_err = store.get_store(id)
            test.is_nil(read_err)
            local _, record_err = log.record(id, { query = "question", strategy = "plain", top_score = 0.1, results = 0 })
            test.is_nil(record_err)
            local token, claim_err = log.claim(id, 1)
            test.is_nil(claim_err)
            test.not_nil(token)
            applied, conflict = store.update_config(id, { self_tuning = true }, fresh.config_snapshot, "lost-token")
            test.is_nil(applied)
            test.eq(conflict:kind(), errors.CONFLICT)
            applied, save_err = store.update_config(id, { self_tuning = true, user_setting = "saved" }, fresh.config_snapshot, token)
            test.is_nil(save_err)
            test.eq(applied, true)
            local row, row_err = store.get_store(id)
            test.is_nil(row_err)
            test.eq(row.config.user_setting, "saved")
            local _, delete_err = store.delete_store(id)
            test.is_nil(delete_err)
        end)
        test.it("keeps bounded observations valid when a UTF-8 character crosses the limit", function()
            local id = uuid.v7()
            local _, create_err = store.create_store(id, "class:embed", {}, nil)
            test.is_nil(create_err)
            local _, record_err = log.record(id, { query = string.rep("q", 499) .. "🌱", strategy = "plain", top_score = 0.1, results = 0 })
            test.is_nil(record_err)
            local samples, read_err = log.weak_samples(id)
            test.is_nil(read_err)
            test.eq(samples[1].query, string.rep("q", 499))
            local _, delete_err = store.delete_store(id)
            test.is_nil(delete_err)
        end)
        test.it("retains a bounded window and grants one tuning lease per interval", function()
            local id = uuid.v7()
            local _, create_err = store.create_store(id, "class:embed", {}, nil)
            test.is_nil(create_err)
            for i = 1, 505 do
                local state, record_err = log.record(id, { query = string.rep("q", 600), strategy = "plain", top_score = 0.1, results = 0 })
                test.is_nil(record_err)
                test.eq(state.observed, i)
            end
            local stats, stats_err = log.stats(id)
            test.is_nil(stats_err)
            test.eq(stats.total, 500)
            local samples, sample_err = log.weak_samples(id)
            test.is_nil(sample_err)
            test.eq(#samples, 12)
            test.eq(#samples[1].query, 500)
            local token, claim_err = log.claim(id, 5)
            test.is_nil(claim_err)
            test.not_nil(token)
            local second, second_err = log.claim(id, 5)
            test.is_nil(second_err)
            test.is_nil(second)
            local _, finish_err = log.finish(id, token, nil, errors.new({ kind = errors.INTERNAL, message = "provider unavailable" }))
            test.is_nil(finish_err)
            local state, err = log.record(id, { query = "query", strategy = "hyde", top_score = 0.8, results = 1 })
            test.is_nil(err)
            test.ok(state.last_error:find("provider unavailable", 1, true))
            local _, delete_err = store.delete_store(id)
            test.is_nil(delete_err)
            local db, db_err = sql.get("app:db")
            test.is_nil(db_err)
            local rows, read_err = db:query("SELECT COUNT(*) AS total FROM kb10_query_log WHERE store_id = $1", { id })
            db:release()
            test.is_nil(read_err)
            test.eq(rows[1].total, 0)
        end)
    end)
end
local cases = test.run_cases(define_tests)
return { run = function(options) return cases(options) end }
