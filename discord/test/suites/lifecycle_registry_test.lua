local test = require("test")
local observer = require("observer")
local names = require("names")
local channel = require("channel")
local time = require("time")
local function define_tests()
    test.describe("Discord lifecycle process registry", function()
        test.it("wakes a hub registered in the observer's declared scope", function()
            local registered, register_err = observer.register()
            test.is_nil(register_err, tostring(register_err))
            test.is_true(registered)
            local result, err = observer.run({ projection = { body = {} }, range = { to_seq = 1 } })
            local _, unregister_err = process.registry.unregister(names.HUB_NAME, process.registry.CONSISTENT)
            test.is_nil(unregister_err, tostring(unregister_err))
            test.is_nil(err, tostring(err))
            test.eq(result.last_seq, 1)
            local inbox = process.inbox()
            local timeout = time.after("2s")
            local selected = channel.select({ inbox:case_receive(), timeout:case_receive() })
            test.eq(selected.channel, inbox, "registered hub receives no lifecycle wake")
            test.eq(selected.value:topic(), "reconcile")
        end)
    end)
end
local run_cases = test.run_cases(define_tests)
return { run = function(options) return run_cases(options) end }
