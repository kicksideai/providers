local test = require("test")
local registry = require("registry")
local contract = require("contract")
local security = require("security")
local fs = require("fs")

local function run(options)
    return test.run_cases(function()
        test.describe("llm-ocr declarations", function()
            test.it("loads the shared picker and transports its declaration through Settings", function()
                local picker = registry.get("kickside.widgets:model_picker_view")
                test.not_nil(picker)
                test.eq(picker.meta.tag_name, "wc-model-picker")
                test.eq(picker.meta.announced, true)
                local widgets_fs = assert(fs.get("kickside.widgets:ui_fs"))
                local settings_fs = assert(fs.get("kickside.settings:ui_fs"))
                test.is_true(#assert(widgets_fs:readfile("model_picker.js")) > 0)
                test.is_true(#assert(settings_fs:readfile("provider.js")) > 0)
                local def = assert(contract.get("kickside.settings:settings"))
                local policy = assert(security.policy("app:admin"))
                local settings = assert(def:with_actor(security.new_actor("ocr-settings-test", {}))
                    :with_scope(security.new_scope({policy})):open())
                local listed = settings:list({namespace = "kickside.llm_ocr"})
                test.eq(listed.success, true)
                local model
                for _, row in ipairs(listed.settings or {}) do
                    if row.key == "ocr_model" then model = row end
                end
                test.not_nil(model)
                test.eq(model.value, "class:fast")
                test.eq(model.control.tag, "wc-model-picker")
                test.eq(model.control.props.capability, "vision")
                test.eq(settings:set({namespace = "kickside.llm_ocr", key = "ocr_model", value = "class:balanced"}).success, true)
                test.eq(settings:get({namespace = "kickside.llm_ocr", key = "ocr_model"}).value, "class:balanced")
                test.eq(settings:unset({namespace = "kickside.llm_ocr", key = "ocr_model"}).success, true)
                test.eq(settings:get({namespace = "kickside.llm_ocr", key = "ocr_model"}).value, "class:fast")
            end)

            test.it("declares the shared vision model value control", function()
                local setting = registry.get("kickside.llm_ocr:setting.ocr_model")
                test.not_nil(setting)
                test.eq(setting.data.value_type, "string")
                test.eq(setting.data.default, "class:fast")
                test.not_nil(setting.data.control)
                test.eq(setting.data.control.tag, "wc-model-picker")
                test.eq(setting.data.control.props.capability, "vision")
            end)

            test.it("registers the universal stage and image OCR default", function()
                local stage = registry.get("kickside.llm_ocr:stage.universal")
                test.not_nil(stage)
                test.eq(stage.data.scope, "universal")
                local setting = registry.get("kickside.llm_ocr:setting.ocr_images")
                test.not_nil(setting)
                test.eq(setting.data.key, "ocr_images")
                test.eq(setting.data.default, true)
            end)
        end)
    end)(options)
end

return { run = run }
