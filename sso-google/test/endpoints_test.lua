local test = require("test")
local registry = require("registry")
local function define_tests()
    test.describe("Instance endpoints", function()
        test.it("declares official defaults through namespace requirements", function()
            local r = registry.get("kickside.sso.providers.google:endpoint_issuer")
            test.not_nil(r)
            test.eq(r.data.default, "https://accounts.google.com")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.sso.providers.google:endpoint_authorize")
            test.not_nil(r)
            test.eq(r.data.default, "https://accounts.google.com/o/oauth2/v2/auth")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.sso.providers.google:endpoint_token")
            test.not_nil(r)
            test.eq(r.data.default, "https://oauth2.googleapis.com/token")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.sso.providers.google:endpoint_userinfo")
            test.not_nil(r)
            test.eq(r.data.default, "https://openidconnect.googleapis.com/v1/userinfo")
            test.is_true(#r.data.targets > 0)
            local r = registry.get("kickside.sso.providers.google:endpoint_jwks")
            test.not_nil(r)
            test.eq(r.data.default, "https://www.googleapis.com/oauth2/v3/certs")
            test.is_true(#r.data.targets > 0)
        end)
    end)
end
local cases = test.run_cases(define_tests)
return { run = function(options) return cases(options) end }
