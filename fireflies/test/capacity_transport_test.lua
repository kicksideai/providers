local test = require("test")
local funcs = require("funcs")
local security = require("security")
local uuid = require("uuid")
return {run = test.run_cases(function()
    test.describe("shared connection capacity transport", function()
        test.it("records one response and gates every consumer before another outbound request", function()
            local executor = funcs.new():with_actor(security.new_actor("capacity-" .. uuid.v7(), {}))
                :with_scope(security.named_scope("wippy.security:process"))
            local result, err = executor:call("app:capacity_transport_probe", {})
            test.is_nil(err, tostring(err))
            test.is_true(result)
        end)
        test.it("reports an unreachable provider as a retryable UNAVAILABLE failure", function()
            local executor = funcs.new():with_actor(security.new_actor("capacity-" .. uuid.v7(), {}))
                :with_scope(security.named_scope("wippy.security:process"))
            local result, err = executor:call("app:capacity_unreachable", {})
            test.is_nil(err, tostring(err))
            test.is_true(result)
        end)
    end)
end)}
